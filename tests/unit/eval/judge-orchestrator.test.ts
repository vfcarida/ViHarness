import { describe, it, expect, vi } from 'vitest';
import * as path from 'node:path';
import * as fs from 'node:fs';
import * as os from 'node:os';
import {
  JudgeInTheLoopOrchestrator,
  type JudgeLoopOptions,
} from '../../../src/infra/eval/judge-orchestrator.js';
import { parseSolveArgs } from '../../../src/cli/commands/solve.js';

describe('JudgeInTheLoopOrchestrator & CLI Integration', () => {
  describe('inferFeedbackFromOutput', () => {
    it('infers AC with score 100 on clean exit code 0', () => {
      const feedback = JudgeInTheLoopOrchestrator.inferFeedbackFromOutput(
        0,
        'Test suite passed. 15 tests executed successfully.',
        '',
      );
      expect(feedback.verdict).toBe('AC');
      expect(feedback.score).toBe(100);
    });

    it('infers CE on compilation errors with non-zero exit code', () => {
      const feedback = JudgeInTheLoopOrchestrator.inferFeedbackFromOutput(
        1,
        '',
        'main.cpp:12:5: error: expected semicolon before "return"',
      );
      expect(feedback.verdict).toBe('CE');
      expect(feedback.compilerErrorOutput).toContain('expected semicolon');
    });

    it('infers TLE when execution times out', () => {
      const feedback = JudgeInTheLoopOrchestrator.inferFeedbackFromOutput(
        1,
        'Execution timed out after 5000ms',
        '',
        true,
      );
      expect(feedback.verdict).toBe('TLE');
    });

    it('infers MLE on memory limit exceeded or heap exhaustion', () => {
      const feedback = JudgeInTheLoopOrchestrator.inferFeedbackFromOutput(
        137,
        '',
        'FATAL ERROR: Ineffective mark-compacts near heap limit Allocation failed - JavaScript heap out of memory',
      );
      expect(feedback.verdict).toBe('MLE');
    });

    it('infers RE on segmentation fault or runtime panic', () => {
      const feedback = JudgeInTheLoopOrchestrator.inferFeedbackFromOutput(
        139,
        '',
        'Segmentation fault (core dumped)',
      );
      expect(feedback.verdict).toBe('RE');
    });

    it('infers WA on exit code 0 if output explicitly contains test failure markers', () => {
      const feedback = JudgeInTheLoopOrchestrator.inferFeedbackFromOutput(
        0,
        'FAIL: test_addition (failed 1 of 5 assertions)',
        '',
      );
      expect(feedback.verdict).toBe('WA');
    });
  });

  describe('executeJudgeCommand', () => {
    it('executes a clean command and parses AC', async () => {
      const cmd = process.platform === 'win32' ? 'cmd /c echo OK' : 'echo OK';
      const res = await JudgeInTheLoopOrchestrator.executeJudgeCommand(cmd, process.cwd(), 10000);

      expect(res.isSuccess).toBe(true);
      expect(res.verdict).toBe('AC');
      expect(res.exitCode).toBe(0);
      expect(res.durationMs).toBeGreaterThanOrEqual(0);
    });

    it('executes a failing command and parses non-AC', async () => {
      const cmd =
        process.platform === 'win32'
          ? 'cmd /c "echo error: syntax failure 1>&2 & exit 1"'
          : 'sh -c "echo error: syntax failure >&2; exit 1"';
      const res = await JudgeInTheLoopOrchestrator.executeJudgeCommand(cmd, process.cwd(), 10000);

      expect(res.isSuccess).toBe(false);
      expect(res.verdict).toBe('CE');
      expect(res.exitCode).toBe(1);
    });

    it('ingests file-based verdict.json when generated by judge command', async () => {
      const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'judge-test-'));
      try {
        const verdictJson = JSON.stringify({
          verdict: 'AC',
          score: 100,
          time_ms: 120,
          summary: 'Accepted on all 10 ACMOJ test vectors',
        });

        const verdictPath = path.join(tmpDir, 'verdict.json');
        fs.writeFileSync(verdictPath, verdictJson, 'utf-8');

        const cmd = process.platform === 'win32' ? 'cmd /c echo done' : 'echo done';
        const res = await JudgeInTheLoopOrchestrator.executeJudgeCommand(cmd, tmpDir, 10000);

        expect(res.isSuccess).toBe(true);
        expect(res.verdict).toBe('AC');
        expect(res.feedback.score).toBe(100);
        expect(res.feedback.timeUsedMs).toBe(120);
      } finally {
        fs.rmSync(tmpDir, { recursive: true, force: true });
      }
    });

    it('ingests inline json from stdout', async () => {
      const cmd = `node -e "console.log(JSON.stringify({verdict:'WA',score:40,failedTestCase:'test_case_3_edge_case_null'}))"`;

      const res = await JudgeInTheLoopOrchestrator.executeJudgeCommand(cmd, process.cwd(), 10000);
      expect(res.verdict).toBe('WA');
      expect(res.feedback.score).toBe(40);
      expect(res.feedback.failedTestCase).toBe('test_case_3_edge_case_null');
    });
  });

  describe('runInteractiveLoop', () => {
    it('succeeds immediately on attempt 1 when judge accepts', async () => {
      const cmd = process.platform === 'win32' ? 'cmd /c echo OK' : 'echo OK';
      const runIteration = vi.fn().mockResolvedValue({ success: true });

      const outcome = await JudgeInTheLoopOrchestrator.runInteractiveLoop({
        judgeCommand: cmd,
        maxRetries: 3,
        cwd: process.cwd(),
        logger: { info: vi.fn(), warn: vi.fn(), error: vi.fn() },
        runIteration,
      });

      expect(outcome.success).toBe(true);
      expect(outcome.totalAttempts).toBe(1);
      expect(outcome.finalVerdict).toBe('AC');
      expect(outcome.history).toHaveLength(1);
      expect(runIteration).toHaveBeenCalledTimes(1);
      expect(runIteration).toHaveBeenCalledWith(1, undefined);
    });

    it('drives iterative repair and succeeds on attempt 2', async () => {
      const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'judge-loop-'));
      try {
        const flagFile = path.join(tmpDir, 'attempt.txt');
        const verdictFile = path.join(tmpDir, 'verdict.json');

        // On attempt 1 -> WA, on attempt 2 -> AC
        const runIteration = vi.fn().mockImplementation(async (attempt: number) => {
          if (attempt === 1) {
            fs.writeFileSync(
              verdictFile,
              JSON.stringify({ verdict: 'WA', failedTestCase: 'test_1' }),
              'utf-8',
            );
          } else {
            fs.writeFileSync(
              verdictFile,
              JSON.stringify({ verdict: 'AC', score: 100 }),
              'utf-8',
            );
          }
          return { success: true };
        });

        const cmd = process.platform === 'win32' ? 'cmd /c echo checked' : 'echo checked';

        const outcome = await JudgeInTheLoopOrchestrator.runInteractiveLoop({
          judgeCommand: cmd,
          maxRetries: 3,
          cwd: tmpDir,
          feedbackFile: verdictFile,
          logger: { info: vi.fn(), warn: vi.fn(), error: vi.fn() },
          runIteration,
        });

        expect(outcome.success).toBe(true);
        expect(outcome.totalAttempts).toBe(2);
        expect(outcome.finalVerdict).toBe('AC');
        expect(outcome.history).toHaveLength(2);
        expect(outcome.history[0]!.verdict).toBe('WA');
        expect(outcome.history[1]!.verdict).toBe('AC');
        expect(runIteration).toHaveBeenCalledTimes(2);
        // Attempt 2 receives diagnostic feedback prompt
        expect(runIteration.mock.calls[1]![1]).toContain('ONLINE JUDGE / BENCHMARK FEEDBACK');
      } finally {
        fs.rmSync(tmpDir, { recursive: true, force: true });
      }
    });

    it('exhausts retries and returns failure outcome when judge persistently fails', async () => {
      const cmd =
        process.platform === 'win32'
          ? 'cmd /c "echo failed test 1>&2 & exit 1"'
          : 'sh -c "echo failed test >&2; exit 1"';
      const runIteration = vi.fn().mockResolvedValue({ success: true });

      const outcome = await JudgeInTheLoopOrchestrator.runInteractiveLoop({
        judgeCommand: cmd,
        maxRetries: 2,
        cwd: process.cwd(),
        logger: { info: vi.fn(), warn: vi.fn(), error: vi.fn() },
        runIteration,
      });

      expect(outcome.success).toBe(false);
      expect(outcome.totalAttempts).toBe(2);
      expect(outcome.finalVerdict).toBe('WA');
      expect(outcome.history).toHaveLength(2);
      expect(runIteration).toHaveBeenCalledTimes(2);
    });
  });

  describe('Solve CLI Options Parsing', () => {
    it('parses --judge-command and --max-judge-retries', () => {
      const args = parseSolveArgs([
        '-p',
        'Solve ACMOJ task 1024',
        '--judge-command',
        'python judge.py',
        '--max-judge-retries',
        '4',
      ]);

      expect(args.judgeCommand).toBe('python judge.py');
      expect(args.maxJudgeRetries).toBe(4);
    });

    it('parses alias --judge-retries', () => {
      const args = parseSolveArgs([
        '-p',
        'Solve ACMOJ task 1024',
        '--judge-command',
        'cargo test',
        '--judge-retries',
        '5',
      ]);

      expect(args.judgeCommand).toBe('cargo test');
      expect(args.maxJudgeRetries).toBe(5);
    });
  });
});
